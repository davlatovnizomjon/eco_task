/** Text for [key] in [lang] with `{name}` placeholders filled from [vars]. */
export function t(lang, key, vars = {}) {
  const text = (TEXTS[lang] ?? TEXTS[DEFAULT_LANG])[key] ?? TEXTS[DEFAULT_LANG][key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

/** Every language's text for [key] — used to recognise a tapped menu button in any language. */
export function allLangs(key) {
  return Object.keys(TEXTS).map((lang) => TEXTS[lang][key]);
}

